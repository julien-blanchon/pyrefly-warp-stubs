#!/usr/bin/env python3
"""Generate the shape-aware ``warp-stubs`` package from an installed Warp.

Warp ships an autogenerated ``warp/__init__.pyi`` of ~11k lines, and the array
and tile classes it refers to live in ``warp/_src/types.py``. Rather than
maintain copies of either by hand, this script reads each stubbed module from
the installed ``warp`` package and merges in the hand-written declarations of
the matching file under ``overrides/``:

    overrides/__init__.pyi             warp/__init__.pyi              -> warp-stubs/__init__.pyi
    overrides/_src/types.pyi           warp/_src/types.py             -> warp-stubs/_src/types.pyi
    overrides/_src/render/render_usd.pyi  warp/_src/render/render_usd.py ...

Every ``.pyi`` file under ``overrides/`` stubs the upstream module at the same
path (``.pyi`` if Warp ships one, else ``.py``). Hand-written stub files that
have no upstream module (``warp-stubs/_shapes.pyi``) live directly in
``warp-stubs/`` and are left alone.

Merge rules, applied to the statements of the upstream module:

* A top-level ``def`` in an override replaces every upstream statement that
  binds the same name (all overloads of a function, a placeholder class, an
  ``import ... as name`` alias), at the position of the first one.
* A top-level ``class`` that also exists upstream as a class is merged: the
  override supplies the header (bases, type parameters, decorators), and each
  override member replaces the upstream members that bind the same name. Other
  upstream members are kept. List a class in ``__generator__["replace"]`` to
  discard the upstream body entirely.
* Any other override statement (import, assignment, type alias) replaces the
  upstream statements binding its names, or is added if there are none.
* ``__generator__ = {"drop": [...]}`` removes upstream bindings outright.
* ``__generator__ = {"rewrite_params": {"tuple": "tuple | Vector[Any, Any]"}}``
  replaces parameter annotations of upstream functions that are exactly the
  key (compared as source text), for APIs whose annotations are narrower than
  what they accept.

In every module except ``__init__.pyi``, Warp's ``@wp.func`` overloading by
redefinition (several ``def f`` with different parameter types) becomes a
``typing.overload`` group; otherwise the last definition would shadow the rest.

An override function or class without a docstring inherits the docstring of
the upstream definition it replaces, so editor hovers keep Warp's docs.

Function bodies in ``_src/types.py`` are kept on purpose: Pyrefly infers
instance attributes (``self.ptr = ...``) and unannotated return types from
bodies even in stub files.
"""

from __future__ import annotations

import argparse
import ast
import importlib.metadata
import importlib.util
import sys
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OVERRIDES = ROOT / "overrides"
OUTPUT = ROOT / "warp-stubs"



def discover_targets(overrides: Path, warp_dir: Path) -> list[tuple[Path, Path]]:
    """(upstream file, override file) pairs, one per ``.pyi`` under ``overrides``."""
    targets = []
    for override in sorted(overrides.rglob("*.pyi")):
        relative = override.relative_to(overrides)
        for upstream in (warp_dir / relative, warp_dir / relative.with_suffix(".py")):
            if upstream.exists():
                targets.append((upstream, override))
                break
        else:
            raise SystemExit(f"{override}: no upstream module {relative.with_suffix('.py')} in {warp_dir}")
    return targets

HEADER = """\
# Generated by tools/generate_stubs.py from warp-lang {version} and overrides/{override}.
# Do not edit: change overrides/ and regenerate.
#
# Upstream portions: SPDX-FileCopyrightText: Copyright (c) 2022 NVIDIA CORPORATION & AFFILIATES.
# SPDX-License-Identifier: Apache-2.0

"""


# ---------------------------------------------------------------------------
# Binding analysis
# ---------------------------------------------------------------------------


def _target_names(target: ast.expr) -> set[str]:
    if isinstance(target, ast.Name):
        return {target.id}
    if isinstance(target, (ast.Tuple, ast.List)):
        return set().union(*(_target_names(elt) for elt in target.elts))
    return set()


def bindings(stmt: ast.stmt) -> set[str]:
    """Names a statement binds in the namespace it appears in."""
    if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return {stmt.name}
    if isinstance(stmt, ast.Assign):
        return set().union(*(_target_names(t) for t in stmt.targets))
    if isinstance(stmt, ast.AnnAssign):
        return _target_names(stmt.target)
    if isinstance(stmt, ast.TypeAlias):
        return _target_names(stmt.name)
    if isinstance(stmt, (ast.Import, ast.ImportFrom)):
        return {
            (alias.asname or alias.name).split(".")[0]
            for alias in stmt.names
            if alias.name != "*"
        }
    if isinstance(stmt, ast.If):
        return set().union(*(bindings(s) for s in [*stmt.body, *stmt.orelse]))
    return set()


def remove_names(stmt: ast.stmt, names: set[str]) -> ast.stmt | None:
    """Return ``stmt`` without its bindings of ``names``, or None if nothing is left."""
    bound = bindings(stmt)
    if not bound & names:
        return stmt
    if isinstance(stmt, (ast.Import, ast.ImportFrom)):
        kept = [
            alias
            for alias in stmt.names
            if (alias.asname or alias.name).split(".")[0] not in names
        ]
        if not kept:
            return None
        stmt.names = kept
        return stmt
    if isinstance(stmt, ast.If):
        stmt.body = remove_all(stmt.body, names) or [ast.Pass()]
        stmt.orelse = remove_all(stmt.orelse, names)
        return stmt
    return None


def remove_all(stmts: Iterable[ast.stmt], names: set[str]) -> list[ast.stmt]:
    out = []
    for stmt in stmts:
        kept = remove_names(stmt, names)
        if kept is not None:
            out.append(kept)
    return out


def docstring_of(node: ast.AST) -> ast.stmt | None:
    body = getattr(node, "body", None)
    if (
        body
        and isinstance(body[0], ast.Expr)
        and isinstance(body[0].value, ast.Constant)
        and isinstance(body[0].value.value, str)
    ):
        return body[0]
    return None


# Looks up the docstring of `name` defined in module `module` of the installed
# Warp package, for overrides that replace a re-export such as
# `from warp._src.context import ones as ones`.
DocResolver = Callable[[str, str], "ast.stmt | None"]


def import_sources(stmt: ast.stmt) -> dict[str, tuple[str, str]]:
    """Map each name an import statement binds to its `(module, original name)`."""
    if isinstance(stmt, ast.ImportFrom):
        module = "." * stmt.level + (stmt.module or "")
        return {a.asname or a.name: (module, a.name) for a in stmt.names if a.name != "*"}
    if isinstance(stmt, ast.Import):
        return {(a.asname or a.name).split(".")[0]: (a.name, "") for a in stmt.names}
    if isinstance(stmt, ast.If):
        sources: dict[str, tuple[str, str]] = {}
        for nested in [*stmt.body, *stmt.orelse]:
            sources.update(import_sources(nested))
        return sources
    return {}


def inherit_docstring(
    override: ast.stmt, upstream: list[ast.stmt], resolve_doc: DocResolver | None
) -> None:
    if not isinstance(override, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return
    if docstring_of(override) is not None:
        return
    for candidate in upstream:
        doc = docstring_of(candidate)
        if doc is None and resolve_doc is not None:
            source = import_sources(candidate).get(override.name)
            if source is not None:
                doc = resolve_doc(*source)
        if doc is not None:
            override.body.insert(0, doc)
            return


# ---------------------------------------------------------------------------
# Merging
# ---------------------------------------------------------------------------


@dataclass
class GeneratorConfig:
    replace: set[str] = field(default_factory=set)
    drop: set[str] = field(default_factory=set)
    rewrite_params: dict[str, str] = field(default_factory=dict)


def pop_config(override: list[ast.stmt]) -> tuple[GeneratorConfig, list[ast.stmt]]:
    config = GeneratorConfig()
    rest = []
    for stmt in override:
        if bindings(stmt) == {"__generator__"}:
            assert isinstance(stmt, (ast.Assign, ast.AnnAssign)) and stmt.value
            raw = ast.literal_eval(stmt.value)
            config.replace = set(raw.get("replace", ()))
            config.drop = set(raw.get("drop", ()))
            config.rewrite_params = dict(raw.get("rewrite_params", {}))
            unknown = set(raw) - {"replace", "drop", "rewrite_params"}
            if unknown:
                raise ValueError(f"unknown __generator__ keys: {sorted(unknown)}")
        else:
            rest.append(stmt)
    return config, rest


def merge_body(
    upstream: list[ast.stmt],
    override: list[ast.stmt],
    *,
    replace_classes: frozenset[str] | set[str] = frozenset(),
    where: str,
    resolve_doc: DocResolver | None = None,
) -> list[ast.stmt]:
    """Merge ``override`` statements into ``upstream``, see the module docstring."""
    result = list(upstream)
    # Placement for statements with no upstream counterpart: imports go after the
    # leading import block, everything else at the end.
    appended_imports: list[ast.stmt] = []
    appended: list[ast.stmt] = []

    # Group override statements by the names they bind, keeping overload groups
    # (several `def`s of one name) together.
    groups: list[tuple[set[str], list[ast.stmt]]] = []
    for stmt in override:
        names = bindings(stmt)
        if (
            groups
            and isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef))
            and groups[-1][0] == names
        ):
            groups[-1][1].append(stmt)
        else:
            groups.append((names, [stmt]))

    for names, stmts in groups:
        if not names:
            # Docstrings and other non-binding statements in an override are not
            # merged; reject them so they cannot silently disappear.
            if all(docstring_of(ast.Module(body=[s], type_ignores=[])) for s in stmts):
                continue
            raise ValueError(
                f"{where}: override statement binds no name: {ast.unparse(stmts[0])}"
            )

        positions = [i for i, s in enumerate(result) if bindings(s) & names]
        replaced = [result[i] for i in positions]

        first = stmts[0]
        # An override import must not silently rebind a name that upstream imports
        # from somewhere else (e.g. `from typing import overload` would shadow
        # Warp's own `wp.overload`). Replacing a placeholder class or a function is
        # fine; that is what overrides are for.
        for name, source in import_sources(first).items():
            for candidate in replaced:
                old = import_sources(candidate).get(name)
                if old is not None and old != source:
                    raise ValueError(
                        f"{where}: override import binds {name!r} from {source[0]}, but upstream "
                        f"imports it from {old[0]}; import it under another name (`as _{name}`)"
                    )
        upstream_class = next(
            (s for s in replaced if isinstance(s, ast.ClassDef) and s.name in names),
            None,
        )
        if (
            isinstance(first, ast.ClassDef)
            and len(stmts) == 1
            and upstream_class is not None
            and first.name not in replace_classes
        ):
            merged_class = merge_class(upstream_class, first, where=where, resolve_doc=resolve_doc)
            new_stmts: list[ast.stmt] = [merged_class]
        else:
            for stmt in stmts:
                inherit_docstring(stmt, replaced, resolve_doc)
            new_stmts = stmts

        if positions:
            insert_at = positions[0]
            kept_before = remove_all(result[:insert_at], names)
            kept_after = remove_all(result[insert_at:], names)
            # Upstream statements binding several names (`from x import a as a, b as b`)
            # are trimmed rather than deleted, so they may survive at `insert_at`.
            result = kept_before + new_stmts + kept_after
        elif isinstance(first, (ast.Import, ast.ImportFrom)):
            appended_imports.extend(new_stmts)
        else:
            appended.extend(new_stmts)

    if appended_imports:
        # After the leading import block (docstring, imports, `if TYPE_CHECKING:`
        # imports), not after the last import anywhere in the module.
        insert_at = 0
        for i, stmt in enumerate(result):
            if isinstance(stmt, (ast.Import, ast.ImportFrom)):
                insert_at = i + 1
            elif i == 0 and docstring_of(ast.Module(body=[stmt], type_ignores=[])):
                insert_at = 1
            elif not isinstance(stmt, ast.If):
                break
        result[insert_at:insert_at] = appended_imports
    return result + appended


def merge_class(
    upstream: ast.ClassDef, override: ast.ClassDef, *, where: str, resolve_doc: DocResolver | None = None
) -> ast.ClassDef:
    upstream_body = list(upstream.body)
    doc = docstring_of(upstream)
    override_body = list(override.body)
    if docstring_of(override) is None and doc is not None:
        override_body.insert(0, doc)
    if doc is not None:
        upstream_body = upstream_body[1:]
    # `...` placeholder bodies carry nothing to merge.
    override_body = [
        s
        for s in override_body
        if not (isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant) and s.value.value is Ellipsis)
    ]
    head = override_body[:1] if override_body and docstring_of(ast.Module(body=override_body[:1], type_ignores=[])) else []
    merged = merge_body(
        upstream_body,
        override_body[len(head):],
        where=f"{where}:{override.name}",
        resolve_doc=resolve_doc,
    )
    override.body = head + merged or [ast.Expr(ast.Constant(Ellipsis))]
    return override


def rewrite_params(upstream: list[ast.stmt], rules: dict[str, str], *, where: str) -> None:
    """Replace parameter annotations that are exactly a rule's key."""
    replacements = {key: ast.parse(value, mode="eval").body for key, value in rules.items()}
    used: set[str] = set()
    for node in ast.walk(ast.Module(body=upstream, type_ignores=[])):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        args = node.args
        for arg in [*args.posonlyargs, *args.args, *args.kwonlyargs]:
            if arg.annotation is not None and (key := ast.unparse(arg.annotation)) in replacements:
                arg.annotation = replacements[key]
                used.add(key)
    if unused := set(rules) - used:
        raise ValueError(f"{where}: rewrite_params rules matched nothing: {sorted(unused)}")


def is_wp_func(node: ast.stmt) -> bool:
    if not isinstance(node, ast.FunctionDef):
        return False
    for decorator in node.decorator_list:
        target = decorator.func if isinstance(decorator, ast.Call) else decorator
        if (isinstance(target, ast.Attribute) and target.attr == "func") or (
            isinstance(target, ast.Name) and target.id == "func"
        ):
            return True
    return False


def group_wp_func_overloads(upstream: list[ast.stmt]) -> list[ast.stmt]:
    """Turn `@wp.func` overloading by redefinition into `typing.overload` groups."""
    by_name: dict[str, list[ast.FunctionDef]] = {}
    for stmt in upstream:
        if is_wp_func(stmt):
            assert isinstance(stmt, ast.FunctionDef)
            by_name.setdefault(stmt.name, []).append(stmt)
    groups = {name: defs for name, defs in by_name.items() if len(defs) > 1}
    if not groups:
        return upstream
    result: list[ast.stmt] = []
    for stmt in upstream:
        if isinstance(stmt, ast.FunctionDef) and stmt.name in groups:
            defs = groups[stmt.name]
            if stmt is defs[0]:
                # Overloads must be adjacent: gather the group at its first definition.
                for definition in defs:
                    definition.decorator_list.insert(0, ast.Name(id="_typing_overload", ctx=ast.Load()))
                result.extend(defs)
            continue
        result.append(stmt)
    marker = ast.ImportFrom(module="typing", names=[ast.alias(name="overload", asname="_typing_overload")], level=0)
    first_non_import = next(
        (i for i, s in enumerate(result) if not isinstance(s, (ast.Import, ast.ImportFrom)) and not docstring_of(ast.Module(body=[s], type_ignores=[]))),
        len(result),
    )
    return result[:first_non_import] + [marker] + result[first_non_import:]


def generate_module(
    upstream_src: str,
    override_src: str,
    *,
    where: str,
    resolve_doc: DocResolver | None = None,
    group_overloads: bool = True,
) -> str:
    upstream = ast.parse(upstream_src).body
    config, override = pop_config(ast.parse(override_src).body)
    missing = config.drop - set().union(*(bindings(s) for s in upstream))
    if missing:
        raise ValueError(f"{where}: __generator__ drops unknown names {sorted(missing)}")
    upstream = remove_all(upstream, config.drop)
    if config.rewrite_params:
        rewrite_params(upstream, config.rewrite_params, where=where)
    if group_overloads:
        upstream = group_wp_func_overloads(upstream)
    merged = merge_body(
        upstream, override, replace_classes=config.replace, where=where, resolve_doc=resolve_doc
    )
    module = ast.Module(body=merged, type_ignores=[])
    ast.fix_missing_locations(module)
    return ast.unparse(module) + "\n"


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def doc_resolver(warp_dir: Path) -> DocResolver:
    cache: dict[str, list[ast.stmt]] = {}

    def resolve(module: str, name: str) -> ast.stmt | None:
        if not module.startswith("warp.") or not name:
            return None
        relative = Path(*module.split(".")[1:])
        for path in (warp_dir / relative.with_suffix(".py"), warp_dir / relative / "__init__.py"):
            if path.exists():
                break
        else:
            return None
        if module not in cache:
            cache[module] = ast.parse(path.read_text()).body
        for node in cache[module]:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name:
                return docstring_of(node)
        return None

    return resolve


def find_warp() -> Path:
    spec = importlib.util.find_spec("warp")
    if spec is None or not spec.submodule_search_locations:
        raise SystemExit("warp is not installed in this interpreter; pass --warp")
    return Path(next(iter(spec.submodule_search_locations)))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--warp", type=Path, help="path to the warp package (default: installed)")
    parser.add_argument("--overrides", type=Path, default=OVERRIDES, help="overrides directory")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="stub package directory to write")
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated files differ from the ones on disk",
    )
    args = parser.parse_args()

    warp_dir: Path = args.warp or find_warp()
    try:
        version = importlib.metadata.version("warp-lang")
    except importlib.metadata.PackageNotFoundError:
        version = (warp_dir.parent / "VERSION.md").read_text().strip() if args.warp else "unknown"

    stale = []
    resolve_doc = doc_resolver(warp_dir)
    for upstream, override in discover_targets(args.overrides, warp_dir):
        output_rel = override.relative_to(args.overrides)
        text = HEADER.format(version=version, override=output_rel) + generate_module(
            upstream.read_text(),
            override.read_text(),
            where=f"overrides/{output_rel}",
            resolve_doc=resolve_doc,
            # `__init__.pyi` declares its overloads explicitly.
            group_overloads=upstream.suffix == ".py",
        )
        output = args.output / output_rel
        if args.check:
            if not output.exists() or output.read_text() != text:
                stale.append(output_rel)
            continue
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text)
        print(f"wrote {output} ({text.count(chr(10))} lines)")

    if stale:
        print(f"stale generated stubs: {', '.join(stale)}; run tools/generate_stubs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
